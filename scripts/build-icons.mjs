#!/usr/bin/env node
// Regenerates js/icons.js from Phosphor Icons (MIT, © 2023 Phosphor Icons —
// https://github.com/phosphor-icons/core). Apple's SF Symbols may not be used on the web, so
// this open set with matching "regular" / "fill" weights stands in for them.
//
//   node scripts/build-icons.mjs
//
// Only a fixed whitelist of SVG tags is copied, so a changed upstream file cannot smuggle markup in.
import { writeFile } from 'node:fs/promises';
import { file } from './lib.mjs';

const SOURCE = 'https://raw.githubusercontent.com/phosphor-icons/core/main/assets';

// our name -> Phosphor name
const SPEC = {
  // tab bar
  sun: 'sun',
  calendar: 'calendar-blank',
  more: 'dots-three-circle',
  // waste groups
  restmuell: 'trash',
  bio: 'leaf',
  papier: 'file-text',
  wertstoff: 'recycle',
  problem: 'warning',
  // interface
  chevronLeft: 'caret-left',
  chevronRight: 'caret-right',
  check: 'check',
  close: 'x',
  share: 'export',
  calendarPlus: 'calendar-plus',
  download: 'download-simple',
  printer: 'printer',
  moon: 'moon',
  info: 'info',
  pin: 'map-pin',
  phone: 'device-mobile',
  plusSquare: 'plus-square',
  moreVertical: 'dots-three-vertical',
  image: 'image',
  menuLines: 'list',
  textSize: 'text-aa',
};
const WEIGHTS = ['regular', 'fill', 'bold'];
const ALLOWED = /^(?:\s*<(?:path|circle|rect|line|polyline|polygon|ellipse)\b[^<>]*\/>)+\s*$/;

async function load(weight, name) {
  const suffix = weight === 'regular' ? '' : `-${weight}`;
  const res = await fetch(`${SOURCE}/${weight}/${name}${suffix}.svg`);
  if (!res.ok) throw new Error(`${weight}/${name}: HTTP ${res.status}`);
  const inner = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(await res.text())?.[1].trim();
  if (!inner || !ALLOWED.test(inner)) throw new Error(`${weight}/${name}: unexpected SVG content`);
  return inner;
}

const entries = [];
for (const [key, name] of Object.entries(SPEC)) {
  const parts = await Promise.all(WEIGHTS.map((w) => load(w, name)));
  entries.push(`  ${key}: {\n${WEIGHTS.map((w, i) => `    ${w}: ${JSON.stringify(parts[i])},`).join('\n')}\n  },`);
}

const output = `// GENERATED by scripts/build-icons.mjs — edit the script's SPEC, not this file.
// Icons: Phosphor Icons, MIT licence, © 2023 Phosphor Icons (licenses/Phosphor-LICENSE.txt).
// Chosen because their regular / fill pairs behave like SF Symbols: a tab is "regular" until
// selected, then "fill". 256-unit grid, painted with currentColor.

const ICONS = {
${entries.join('\n')}
};

const svg = (inner) =>
  \`<svg class="ico" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" focusable="false">\${inner}</svg>\`;

const draw = (entry, weight) => svg(entry[weight] ?? entry.regular);

// Waste groups default to the solid glyph (white on a coloured tile); unknown groups fall back to the bin.
export const groupIcon = (group, weight = 'fill') => draw(ICONS[group] ?? ICONS.restmuell, weight);
export const uiIcon = (name, weight = 'regular') => draw(ICONS[name], weight);

// The bare paths (no <svg> wrapper), for drawing a glyph inside a larger illustration.
export const groupGlyph = (group, weight = 'fill') => (ICONS[group] ?? ICONS.restmuell)[weight];
`;

await writeFile(file('js', 'icons.js'), output);
console.log(`js/icons.js: ${Object.keys(SPEC).length} icons x ${WEIGHTS.length} weights`);
